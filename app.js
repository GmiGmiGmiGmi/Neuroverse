function mascotAnswer(text){
  const q=text.trim(); if(!q)return;
  const log=document.getElementById("neroChatLog");
  const cfg=mascotConfig(activeProduct);
  const u=document.createElement("div");u.className="nero-msg user";u.textContent=q;log.appendChild(u);
  mascotBusy=true;
  if(activeProduct==="neurostrip") setNeroExpression("thinking");

  let key=findRoute(q);

  // Prioritise the active product for ambiguous wording.
  if(!/neuronode|neurostrip|grid 3|aac|controller|dysphagia/i.test(q)){
    if(activeProduct==="neuronode"){
      const nnCandidate=searchMap.find(([terms])=>terms.startsWith("neuronode") && terms.split(" ").some(t=>q.toLowerCase().includes(t)));
      if(nnCandidate) key=nnCandidate[1];
    } else {
      const nsCandidate=searchMap.find(([terms])=>terms.startsWith("neurostrip") && terms.split(" ").some(t=>q.toLowerCase().includes(t)));
      if(nsCandidate) key=nsCandidate[1];
    }
  }

  setTimeout(()=>{
    const currentCfg=mascotConfig(activeProduct);
    const a=document.createElement("div");a.className="nero-msg assistant";
    if(key){
      const targetProduct=routeProductForKey(key);
      const targetName=mascotConfig(targetProduct).name;
      const productName=targetProduct==="neuronode"?"NeuroNode / AAC":"NeuroStrip";
      a.innerHTML=`<strong>${currentCfg.name}:</strong> I found a ${productName} guide that matches that question. <button class="nero-open-guide" data-key="${key}">Open guide →</button>`;
      // If user is clearly asking about the other product, switch mascots before they open it.
      if(targetProduct!==activeProduct){
        a.innerHTML+=` <button class="nero-open-guide switch-product" data-key="${key}">Switch to ${targetName} →</button>`;
      }
    } else {
      a.innerHTML=`<strong>${currentCfg.name}:</strong> I’m not confident that question matches one of the documented support flows. Try including the product name and symptom, or contact Control Bionics Support.`;
    }
    log.appendChild(a);log.scrollTop=log.scrollHeight;mascotBusy=false;
    if(activeProduct==="neurostrip") setNeroExpression(key?(Math.random()>.5?"excited":"proud"):"curious");
    a.querySelectorAll(".nero-open-guide").forEach(b=>b.onclick=()=>openGuide(b.dataset.key));
  },500);
}

