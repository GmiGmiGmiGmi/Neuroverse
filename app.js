function buildJump(g){
  const labels={
    "ns-skinprep":"Skin preparation","ns-placement":"EMG placement","ns-connections":"Connect NeuroStrip","ns-patient":"Client Manager","ns-protocols":"Protocols","ns-session":"Start session","ns-graph":"Live graph","ns-review":"Review progress"
  };
  return `<div class="choice-grid">${g.jump.map(k=>`<button class="choice" data-jump="${k}">${labels[k]||k}</button>`).join("")}</div>`;
}
function renderGuide(key){
  const g=guides[key];
  let html=`<span class="eyebrow">${key.startsWith("nn-")?"NEURONODE SUPPORT GUIDE":"NEUROSTRIP SUPPORT GUIDE"}</span><h2>${g.title}</h2>`;
  if(g.carousel) html+=`<div class="guide-carousel" data-carousel-key="${key}"></div>`;
  if(g.jump) html+=buildJump(g);
  if(g.warning) html+=`<div class="callout warning">${g.warning}</div>`;
  html+=`<div class="source-note">Source basis: ${g.source}</div>`;
  return html;
}
function openGuide(key,push=true){
  if(push&&current&&current!==key) history.push(current);
  current=key;
  setProductContext(key.startsWith("nn-")?"neuronode":"neurostrip");
  content.innerHTML=renderGuide(key);
  modal.classList.add("open"); modal.setAttribute("aria-hidden","false");
  document.body.style.overflow="hidden";
  initCarousel(key);
  content.querySelectorAll("[data-jump]").forEach(b=>b.onclick=()=>openGuide(b.dataset.jump,true));
}
function closeGuide(){modal.classList.remove("open");modal.setAttribute("aria-hidden","true");document.body.style.overflow="";current=null;history=[]}
